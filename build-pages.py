def mark_active(header, key):
    """Flag the nav item this page belongs to, whichever attribute order it uses."""
    header = header.replace('nav__link is-active', 'nav__link')  # clear the homepage's own
    def fix(m):
        tag = m.group(0).replace('class="nav__link', 'class="nav__link is-active', 1)
        return tag.replace('>', ' aria-current="page">', 1)
    return re.sub(r'<a[^>]*data-nav="%s"[^>]*>' % re.escape(key), fix, header, count=1)

def crumbs(*items):
    """BreadcrumbList JSON-LD from (name, slug) pairs."""
